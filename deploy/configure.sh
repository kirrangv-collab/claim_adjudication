#!/usr/bin/env bash
# Create deploy/.env for a ClaimLab deployment, with strong random secrets.
#
# Usage:
#   bash deploy/configure.sh --domain claimlab.duckdns.org [--stack lite|full]
#                            [--no-demo] [--demo-password PASSWORD] [--force]
#
#   --domain         Public hostname for HTTPS (use "localhost" for a local test).
#   --stack          lite (default, ~1 GB RAM) or full (adds Qdrant + Neo4j, ~4 GB RAM).
#   --no-demo        Do not run as a public demo (no demo accounts on the login page).
#   --demo-password  Password shown publicly for the demo accounts (default: try-claimlab).
#   --force          Overwrite an existing .env (only before the first start: the
#                    database keeps the password it was created with).
set -euo pipefail
cd "$(dirname "$0")"

DOMAIN="" STACK="lite" DEMO="true" DEMO_PASSWORD="try-claimlab" FORCE="false"
while [ $# -gt 0 ]; do
  case "$1" in
    --domain) DOMAIN="${2:-}"; shift 2 ;;
    --stack) STACK="${2:-}"; shift 2 ;;
    --no-demo) DEMO="false"; shift ;;
    --demo-password) DEMO_PASSWORD="${2:-}"; shift 2 ;;
    --force) FORCE="true"; shift ;;
    -h|--help) sed -n '2,15p' "$(basename "$0")"; exit 0 ;;
    *) echo "Unknown option: $1 (see --help)" >&2; exit 1 ;;
  esac
done

if [ -z "$DOMAIN" ]; then
  echo "--domain is required, e.g. --domain claimlab.duckdns.org (or --domain localhost to test)" >&2
  exit 1
fi
case "$STACK" in lite|full) ;; *) echo "--stack must be 'lite' or 'full'" >&2; exit 1 ;; esac
if [ "$DEMO" = "true" ] && [ "${#DEMO_PASSWORD}" -lt 8 ]; then
  echo "--demo-password must be at least 8 characters" >&2
  exit 1
fi
if [ -f .env ] && [ "$FORCE" != "true" ]; then
  echo "deploy/.env already exists. Use --force to overwrite it (only before the first start)." >&2
  exit 1
fi

rand() { openssl rand -hex 24; }
if [ "$STACK" = "full" ]; then
  PROFILES="full" VECTOR="qdrant" GRAPH="neo4j"
else
  PROFILES="" VECTOR="memory" GRAPH="memory"
fi

umask 077
cat > .env <<EOF
# Generated by deploy/configure.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private.
DOMAIN=$DOMAIN
COMPOSE_PROFILES=$PROFILES
CLAIMLAB_VECTOR_BACKEND=$VECTOR
CLAIMLAB_GRAPH_BACKEND=$GRAPH
POSTGRES_PASSWORD=$(rand)
JWT_SECRET=$(rand)$(rand)
NEO4J_PASSWORD=$(rand)
CLAIMLAB_PUBLIC_DEMO=$DEMO
CLAIMLAB_DEMO_PASSWORD=$( [ "$DEMO" = "true" ] && echo "$DEMO_PASSWORD" )
CAF_MODEL_API_KEY=
EOF

echo "Wrote deploy/.env (domain: $DOMAIN, stack: $STACK, public demo: $DEMO)."
echo "Start the site:  cd deploy && docker compose up -d --build"
